"""Running hugo for one target.

Hugo can not filter pages on front matter, so myweb does that.  For each
build it writes an extra hugo config that:

- excludes, via the content mount, every bundle whose audience is not
  served by the target, and every protected bundle if the target lacks
  auth;
- marks, via cascade, unlisted and protected bundles to be rendered but
  never listed (indices, RSS, sitemap) and sets their "visibility" param;
- sets, via cascade, each bundle's "source" param to the name its org
  source is published under, for the theme to link.
"""

from __future__ import annotations

import json
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from .config import Config, Target, xdg_dir
from .site import Bundle, bundles


class HugoError(Exception):
    pass


@dataclass
class Plan:
    """What one target gets."""

    target: Target
    included: list[Bundle] = field(default_factory=list)
    excluded: list[tuple[Bundle, str]] = field(default_factory=list)
    hidden: list[tuple[Bundle, str]] = field(default_factory=list)

    @property
    def protected(self) -> list[Bundle]:
        return [b for b, vis in self.hidden if vis == "protected"]


def plan(cfg: Config, target: Target, drafts: bool = False) -> Plan:
    result = Plan(target)
    for bundle in bundles(cfg):
        meta = bundle.meta()
        why = ""
        if meta.audience not in target.audience:
            why = f"audience {meta.audience}"
        elif meta.visibility == "protected" and not target.auth:
            why = "protected, target has no auth"
        elif meta.draft and not drafts:
            why = "draft"
        if why:
            result.excluded.append((bundle, why))
            continue
        result.included.append(bundle)
        if meta.visibility in ("unlisted", "protected"):
            result.hidden.append((bundle, meta.visibility))
    return result


def _q(text: str) -> str:
    return json.dumps(text)  # a JSON string is a valid TOML basic string


def config_text(p: Plan) -> str:
    lines = ["# Generated by myweb for target " + p.target.name, ""]
    excludes = [f"! {b.content_rel}/**" for b, _ in p.excluded]
    lines += [
        "[[module.mounts]]",
        'source = "content"',
        'target = "content"',
    ]
    if excludes:
        lines.append("files = [" + ", ".join(_q(e) for e in excludes) + "]")
    lines.append("")
    hidden = {b.name: vis for b, vis in p.hidden}
    for bundle in p.included:
        lines.append("[[cascade]]")
        if bundle.name in hidden:
            lines += ["[cascade.build]", 'list = "never"']
        lines += ["[cascade.params]", f"source = {_q(bundle.source_name)}"]
        if bundle.name in hidden:
            lines.append(f"visibility = {_q(hidden[bundle.name])}")
        lines += [
            "[cascade.target]",
            f"path = {_q('/' + bundle.content_rel)}",
            "",
        ]
    return "\n".join(lines)


def write_config(p: Plan) -> Path:
    path = xdg_dir("cache") / "hugo" / f"{p.target.name}.toml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(config_text(p))
    return path


def base_args(cfg: Config, p: Plan, drafts: bool) -> list[str]:
    args = [
        *cfg.hugo,
        "--source", str(cfg.site),
        "--environment", p.target.environment,
        "--config", str(write_config(p)),
    ]
    if drafts:
        args.append("--buildDrafts")
    if p.target.base_url:
        args += ["--baseURL", p.target.base_url]
    return args


def base_url(cfg: Config, p: Plan) -> str:
    """The base URL hugo resolves for this plan's target."""
    proc = subprocess.run(
        base_args(cfg, p, drafts=False) + ["config", "--format", "json"],
        capture_output=True,
        text=True,
    )
    if proc.returncode:
        raise HugoError(proc.stderr.strip())
    return json.loads(proc.stdout).get("baseurl", "/")


def build(cfg: Config, p: Plan, stage: Path, drafts: bool = False) -> str:
    """Build the site per plan into STAGE, return hugo's output."""
    stage.mkdir(parents=True, exist_ok=True)
    args = base_args(cfg, p, drafts) + [
        "--destination", str(stage),
        "--cleanDestinationDir",
        "--logLevel=warn",
    ]
    proc = subprocess.run(args, capture_output=True, text=True)
    if proc.returncode:
        raise HugoError(proc.stderr.strip() or proc.stdout.strip())
    return proc.stdout + proc.stderr


def server_args(cfg: Config, p: Plan, port: int) -> list[str]:
    return base_args(cfg, p, drafts=True) + [
        "server",
        "--port", str(port),
        "--baseURL", f"http://localhost:{port}/",
        "--appendPort=false",
        "--navigateToChanged",
    ]
