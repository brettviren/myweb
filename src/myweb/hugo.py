"""Running hugo for one target.

Hugo can not filter pages on front matter, so myweb does that.  For each
build it writes an extra hugo config that:

- excludes, via the content mount, every bundle whose audience is not
  served by the target, and every protected bundle if the target lacks
  auth;
- marks, via cascade, unlisted and protected bundles to be rendered but
  never listed (indices, RSS, sitemap) and sets their "visibility" param;
- sets, via cascade, each bundle's "source" param to the name its org
  source is published under, for the theme to link;
- mounts the talks the target gets, written by talkpages.py, as
  content/talks, and the listing pages of its artifacts (artifacts.py) as
  content/artifacts.
"""

from __future__ import annotations

import json
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from . import access, artifacts, orgmeta, talkpages
from .config import Config, Target, xdg_dir
from .site import Bundle, bundles


class HugoError(Exception):
    pass


@dataclass
class Plan:
    """What one target gets."""

    target: Target
    #: What the plan is for: "build", "check" or "server".  Each use has its
    #: own generated config and talks, since a running hugo server watches
    #: its config and a rewrite mid-build deadlocks it on the build lock.
    use: str = "build"
    included: list[Bundle] = field(default_factory=list)
    excluded: list[tuple[Bundle, str]] = field(default_factory=list)
    hidden: list[tuple[Bundle, str]] = field(default_factory=list)
    #: Of each included bundle, by name: its meta and access realm.
    meta: dict[str, orgmeta.Meta] = field(default_factory=dict)
    realm: dict[str, access.Realm] = field(default_factory=dict)
    #: Talks, which share meta, realm and hidden with bundles.
    talks: list[talkpages.Talk] = field(default_factory=list)
    talks_excluded: list[tuple[talkpages.Talk, str]] = field(default_factory=list)
    #: Artifacts, likewise, copied verbatim rather than rendered.
    artifacts: list[artifacts.Artifact] = field(default_factory=list)
    artifacts_excluded: list[tuple[artifacts.Artifact, str]] = field(default_factory=list)

    @property
    def protected(self) -> list:
        """Protected bundles and talks."""
        return [b for b, vis in self.hidden if vis == "protected"]

    @property
    def pages(self) -> list:
        """Every included page: bundles, talks, then artifacts."""
        return [*self.included, *self.talks, *self.artifacts]

    @property
    def all_excluded(self) -> list:
        return [*self.excluded, *self.talks_excluded, *self.artifacts_excluded]


def _why_not(target: Target, meta: orgmeta.Meta, drafts: bool) -> str:
    """Why a page with META is not built for TARGET, "" if it is."""
    if meta.audience not in target.audience:
        return f"audience {meta.audience}"
    if meta.visibility == "protected" and not target.auth:
        return "protected, target has no auth"
    if meta.draft and not drafts:
        return "draft"
    if access.page_realm(target, meta) is None:
        return f"access realm {meta.access} not on target"
    return ""


def plan(cfg: Config, target: Target, drafts: bool = False, use: str = "build") -> Plan:
    result = Plan(target, use)
    for bundle in bundles(cfg):
        meta = bundle.meta()
        if why := _why_not(target, meta, drafts):
            result.excluded.append((bundle, why))
            continue
        result.included.append(bundle)
        _admit(result, bundle, meta)
    for talk in talkpages.load(cfg.talks_dest, cfg.talks) if target.talks else []:
        if why := _why_not(target, talk.meta, drafts):
            result.talks_excluded.append((talk, why))
            continue
        result.talks.append(talk)
        _admit(result, talk, talk.meta)
    for art in artifacts.load(artifacts.source_dir(cfg.site, cfg.artifacts), cfg.artifacts):
        if why := _why_not(target, art.meta, drafts):
            result.artifacts_excluded.append((art, why))
            continue
        result.artifacts.append(art)
        _admit(result, art, art.meta)
    return result


def _admit(result: Plan, page, meta: orgmeta.Meta) -> None:
    result.meta[page.name] = meta
    result.realm[page.name] = access.page_realm(result.target, meta)
    if meta.visibility in ("unlisted", "protected"):
        result.hidden.append((page, meta.visibility))


def _q(text: str) -> str:
    return json.dumps(text)  # a JSON string is a valid TOML basic string


def config_text(p: Plan) -> str:
    lines = ["# Generated by myweb for target " + p.target.name, ""]
    excludes = [f"! {b.content_rel}/**" for b, _ in p.excluded]
    lines += [
        "[[module.mounts]]",
        'source = "content"',
        'target = "content"',
    ]
    if excludes:
        lines.append("files = [" + ", ".join(_q(e) for e in excludes) + "]")
    lines.append("")
    if p.talks:
        lines += [
            "[[module.mounts]]",
            f"source = {_q(str(talks_dir(p)))}",
            f'target = "content/{talkpages.SECTION}"',
            "",
        ]
    lines += [
        "[[module.mounts]]",
        f"source = {_q(str(artifacts_dir(p)))}",
        f'target = "content/{artifacts.SECTION}"',
        "",
    ]
    hidden = {b.name: vis for b, vis in p.hidden}
    for bundle in p.included:
        lines.append("[[cascade]]")
        if bundle.name in hidden:
            lines += ["[cascade.build]", 'list = "never"']
        lines += ["[cascade.params]", f"source = {_q(bundle.source_name)}"]
        if bundle.name in hidden:
            lines.append(f"visibility = {_q(hidden[bundle.name])}")
        lines += [
            "[cascade.target]",
            f"path = {_q('/' + bundle.content_rel)}",
            "",
        ]
    return "\n".join(lines)


def _key(p: Plan) -> str:
    return p.target.name if p.use == "build" else f"{p.target.name}-{p.use}"


def talks_dir(p: Plan) -> Path:
    return xdg_dir("cache") / "talks" / _key(p)


def artifacts_dir(p: Plan) -> Path:
    return xdg_dir("cache") / "artifacts" / _key(p)


def write_config(p: Plan) -> Path:
    """Write the extra hugo config, and the talks and artifacts it mounts."""
    talkpages.write(p.talks, talks_dir(p))
    artifacts.write(p.artifacts, artifacts_dir(p))
    path = xdg_dir("cache") / "hugo" / f"{_key(p)}.toml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(config_text(p))
    return path


def base_args(cfg: Config, p: Plan, drafts: bool) -> list[str]:
    args = [
        *cfg.hugo,
        "--source", str(cfg.site),
        "--environment", p.target.environment,
        "--config", str(write_config(p)),
    ]
    if drafts:
        args.append("--buildDrafts")
    if p.target.base_url:
        args += ["--baseURL", p.target.base_url]
    return args


def base_url(cfg: Config, p: Plan) -> str:
    """The base URL hugo resolves for this plan's target."""
    proc = subprocess.run(
        base_args(cfg, p, drafts=False) + ["config", "--format", "json"],
        capture_output=True,
        text=True,
    )
    if proc.returncode:
        raise HugoError(proc.stderr.strip())
    return json.loads(proc.stdout).get("baseurl", "/")


def build(cfg: Config, p: Plan, stage: Path, drafts: bool = False) -> str:
    """Build the site per plan into STAGE, return hugo's output."""
    stage.mkdir(parents=True, exist_ok=True)
    args = base_args(cfg, p, drafts) + [
        "--destination", str(stage),
        "--cleanDestinationDir",
        "--logLevel=warn",
    ]
    proc = subprocess.run(args, capture_output=True, text=True)
    if proc.returncode:
        raise HugoError(proc.stderr.strip() or proc.stdout.strip())
    return proc.stdout + proc.stderr


def server_args(cfg: Config, p: Plan, port: int) -> list[str]:
    return base_args(cfg, p, drafts=True) + [
        "server",
        "--port", str(port),
        "--baseURL", f"http://localhost:{port}/",
        "--appendPort=false",
        "--navigateToChanged",
    ]
